import * as Fs from "node:fs/promises";
import * as Path from "node:path";

import gitDiff from "git-diff";
import * as Prettier from "prettier";
import { Project, SourceFile, StructureKind, VariableDeclarationKind } from "ts-morph";

import { CHECK_MARK, INDEX_FILE_NAME, SCHEMA_FILE_NAME, VERSION_PREFIX } from "../../constants.js";
import type { ResolvedConfiguration } from "../../types.js";
import { type StepInfo, extractStepInfos, getIndexFilePath } from "../../utils.js";

export async function generateIndexFile(config: ResolvedConfiguration) {
	console.log(`\nGenerating steps index file...`);

	const indexFile = await createIndexFile(config);
	await Fs.writeFile(getIndexFilePath(config), indexFile, "utf-8");

	console.log(`Generated steps index file successfully!`);
}

export async function validateIndexFile(config: ResolvedConfiguration) {
	const referenceFile = await createIndexFile(config);
	const currentFile = await Fs.readFile(getIndexFilePath(config), "utf-8");

	const diff = gitDiff(referenceFile, currentFile, { color: true, noHeaders: true });

	if (diff !== undefined) {
		throw new Error(`Inconsistency in ${Path.join(config.stepsDirPath, INDEX_FILE_NAME)}. \nDiff:\n ${diff}`);
	}

	console.log(`${CHECK_MARK} Validated index file synchronization!`);
}

async function createIndexFile(config: ResolvedConfiguration) {
	const indexFilePath = getIndexFilePath(config);
	const sourceFile = new Project().createSourceFile(indexFilePath, "", { overwrite: true });
	const stepInfos = await extractStepInfos(config);

	addImportStatements(sourceFile, stepInfos, config.schema);
	addMigrationStepVariable(sourceFile, stepInfos, config.schema);

	return format(indexFilePath, sourceFile.getFullText());
}

async function format(filePath: string, textSource: string): Promise<string> {
	const options = await Prettier.resolveConfig(filePath);

	return Prettier.format(textSource, { ...options, parser: "typescript" });
}

function addImportStatements(stepConfigFile: SourceFile, stepInfos: StepInfo[], schema?: boolean) {
	stepConfigFile.addStatements([`/* This file is automatically generated from the migration tool utils package */`]);

	stepConfigFile.addImportDeclaration({
		moduleSpecifier: "@com.mgmtp.a12.migrationtool/migrationtool-core/types",
		isTypeOnly: true,
		namedImports: ["MigrationStep"],
		trailingTrivia: "\n"
	});

	for (const stepInfo of stepInfos) {
		if (schema) {
			stepConfigFile.addImportDeclaration({
				defaultImport: toSchemaIdentifier(stepInfo.version),
				moduleSpecifier: `./${VERSION_PREFIX}${stepInfo.version}/${SCHEMA_FILE_NAME}`,
				attributes: [{ name: "type", value: "json" }],
				leadingTrivia: stepInfo.shouldAppendNewline ? "\n" : undefined
			});

			stepConfigFile.addStatements("\n");
			stepConfigFile.addStatements("\n");
		}

		if (stepInfo.transform) {
			stepConfigFile.addImportDeclaration({
				defaultImport: toTransformIdentifier(stepInfo.version),
				moduleSpecifier: `./${VERSION_PREFIX}${stepInfo.version}/transform.js`,
				trailingTrivia: "\n"
			});
		}
	}
}

function addMigrationStepVariable(stepConfigFile: SourceFile, stepInfos: StepInfo[], schema?: boolean): void {
	const migrationSteps = stepInfos
		.flatMap(({ shouldAppendNewline, version, transform }) => {
			const config = [
				`version: "${version}"`,
				schema ? `schema: ${toSchemaIdentifier(version)}` : undefined,
				transform ? `transform: ${toTransformIdentifier(version)}` : undefined
			]
				.filter(Boolean)
				.join(", ");

			return shouldAppendNewline ? ["", `{ ${config} },`] : `{ ${config} },`;
		})
		.join("\n");

	stepConfigFile.addVariableStatement({
		declarationKind: VariableDeclarationKind.Const,
		declarations: [
			{
				name: "MIGRATION_STEPS",
				type: "MigrationStep[]",
				initializer: `[\n${migrationSteps}\n]`
			}
		],
		isExported: true,
		kind: StructureKind.VariableStatement
	});
}

function toTransformIdentifier(version: string): string {
	return toIdentifier(`Transform_${version}`);
}

function toSchemaIdentifier(version: string): string {
	return toIdentifier(`Schema_${version}`);
}

function toIdentifier(string: string): string {
	return string.replace(/\W/g, "_");
}
